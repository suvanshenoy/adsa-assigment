"""
KMP String Matching Experiment Runner
Group 6: Comparative Performance Analysis of Naive String Matching and KMP
Author: USN 23 (Knuth-Morris-Pratt Algorithm & LPS Construction)

Executes KMP string matching on all multilingual pattern workloads generated by USN 21.
Measures LPS array construction time and KMP search execution time strictly separately.
Counts character comparisons during searching.
Validates correctness against USN 21's expected results and Python's reference search.
Generates per-workload and consolidated CSV results, summary JSON, and execution logs.
"""

import csv
import json
import logging
import sys
import time
from pathlib import Path

# Setup path to import USN 23's KMP and LPS modules
CURRENT_DIR = Path(__file__).resolve().parent
REPO_ROOT = CURRENT_DIR.parent.parent

if str(CURRENT_DIR) not in sys.path:
    sys.path.insert(0, str(CURRENT_DIR))

from lps import compute_lps
from kmp import kmp_search

# Paths configuration
QUERY_DIR = REPO_ROOT / "queries"
RESULTS_DIR = REPO_ROOT / "results"
KMP_RESULTS_DIR = RESULTS_DIR / "kmp"
KMP_RESULTS_DIR.mkdir(parents=True, exist_ok=True)

# Logger setup
LOG_FILE = KMP_RESULTS_DIR / "kmp_experiments.log"
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.FileHandler(LOG_FILE, encoding="utf-8"),
        logging.StreamHandler(sys.stdout),
    ],
)
logger = logging.getLogger("KMP_Runner")


def reference_find_all(text, pattern):
    """
    Python reference search finding all 0-based occurrences
    with support for overlapping matches.
    """
    if not pattern:
        return []
    matches = []
    start = 0
    while True:
        pos = text.find(pattern, start)
        if pos == -1:
            break
        matches.append(pos)
        start = pos + 1
    return matches


def process_workload(pattern_file: Path):
    """
    Process a single pattern CSV file generated by USN 21.
    Returns:
        records (list of dict): Experimental benchmark records.
        stats (dict): Workload-level statistics.
    """
    logger.info(f"Processing workload: {pattern_file.name}")

    records = []
    total_comparisons = 0
    total_lps_time = 0.0
    total_search_time = 0.0
    successful_count = 0
    unsuccessful_count = 0
    passed_validation = 0
    failed_validation = 0

    with open(pattern_file, mode="r", encoding="utf-8-sig", newline="") as fp:
        reader = csv.DictReader(fp)
        for idx, row in enumerate(reader, start=1):
            language = row["language"]
            sample_size = int(row["sample_size"])
            pattern_category = row["pattern_category"]
            pattern_type = row["pattern_type"]
            target_title = row["target_title"]
            pattern = row["pattern"]
            pattern_length = int(row["pattern_length"])
            expected_found = row["expected_found"].lower() == "true"
            expected_first_pos = int(row["expected_position"])

            # Unique Query ID
            stem = pattern_file.stem.replace("_patterns", "")
            query_id = f"KMP_{stem}_{idx:04d}"

            # Step 4: Measure LPS construction time separately
            t0_lps = time.perf_counter()
            lps_arr = compute_lps(pattern)
            t1_lps = time.perf_counter()
            lps_time = t1_lps - t0_lps

            # Step 4: Measure KMP search execution time separately (using precomputed LPS)
            t0_search = time.perf_counter()
            actual_matches, comparisons = kmp_search(target_title, pattern, lps=lps_arr)
            t1_search = time.perf_counter()
            search_time = t1_search - t0_search

            actual_found = len(actual_matches) > 0

            # Step 6: Reference verification
            ref_matches = reference_find_all(target_title, pattern)

            # Validation against expected values
            match_status_correct = (actual_found == expected_found)
            matches_correct = (actual_matches == ref_matches)
            first_pos_correct = True
            if expected_found:
                first_pos_correct = (len(actual_matches) > 0 and actual_matches[0] == expected_first_pos)

            is_correct = match_status_correct and matches_correct and first_pos_correct
            correctness_status = "PASSED" if is_correct else "FAILED"

            if is_correct:
                passed_validation += 1
            else:
                failed_validation += 1
                logger.error(
                    f"Validation failure for query {query_id}: "
                    f"text={target_title!r}, pattern={pattern!r}, "
                    f"actual={actual_matches}, ref={ref_matches}, expected_pos={expected_first_pos}"
                )

            if actual_found:
                successful_count += 1
            else:
                unsuccessful_count += 1

            total_comparisons += comparisons
            total_lps_time += lps_time
            total_search_time += search_time

            records.append({
                "query_id": query_id,
                "language": language,
                "source_title": target_title,
                "pattern": pattern,
                "pattern_length": pattern_length,
                "expected_match_positions": json.dumps(ref_matches),
                "actual_match_positions": json.dumps(actual_matches),
                "expected_match_status": expected_found,
                "actual_match_status": actual_found,
                "correctness_status": correctness_status,
                "lps_array": json.dumps(lps_arr),
                "lps_construction_time": f"{lps_time:.9e}",
                "kmp_search_time": f"{search_time:.9e}",
                "kmp_character_comparisons": comparisons,
                "sample_size": sample_size,
                "pattern_category": pattern_category,
                "pattern_type": pattern_type,
                "time_unit": "seconds",
            })

    stats = {
        "workload": pattern_file.name,
        "language": language,
        "sample_size": sample_size,
        "total_records": len(records),
        "successful_patterns": successful_count,
        "unsuccessful_patterns": unsuccessful_count,
        "passed_cases": passed_validation,
        "failed_cases": failed_validation,
        "total_comparisons": total_comparisons,
        "mean_comparisons": total_comparisons / len(records) if records else 0,
        "total_lps_construction_time_sec": total_lps_time,
        "mean_lps_construction_time_sec": total_lps_time / len(records) if records else 0,
        "total_kmp_search_time_sec": total_search_time,
        "mean_kmp_search_time_sec": total_search_time / len(records) if records else 0,
    }

    logger.info(
        f"Finished {pattern_file.name}: {len(records)} records | "
        f"Passed: {passed_validation} | Failed: {failed_validation} | "
        f"Total Comps: {total_comparisons:,} | "
        f"LPS Time: {total_lps_time:.6f}s | Search Time: {total_search_time:.6f}s"
    )

    return records, stats


def main():
    logger.info("Starting KMP Multilingual Wikipedia Experiment Execution")
    pattern_files = sorted(QUERY_DIR.glob("*_patterns.csv"))

    if not pattern_files:
        raise FileNotFoundError(f"No pattern CSV files found in {QUERY_DIR}")

    all_records = []
    workload_summaries = {}

    fieldnames = [
        "query_id",
        "language",
        "source_title",
        "pattern",
        "pattern_length",
        "expected_match_positions",
        "actual_match_positions",
        "expected_match_status",
        "actual_match_status",
        "correctness_status",
        "lps_array",
        "lps_construction_time",
        "kmp_search_time",
        "kmp_character_comparisons",
        "sample_size",
        "pattern_category",
        "pattern_type",
        "time_unit",
    ]

    for p_file in pattern_files:
        records, stats = process_workload(p_file)
        all_records.extend(records)
        workload_summaries[p_file.stem] = stats

        # Save individual workload result CSV
        workload_out = KMP_RESULTS_DIR / f"{p_file.stem}_results.csv"
        with open(workload_out, "w", encoding="utf-8", newline="") as fp:
            writer = csv.DictWriter(fp, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(records)

    # Save consolidated master benchmark CSV in results/kmp/ and results/
    master_csv_kmp = KMP_RESULTS_DIR / "kmp_benchmark_results.csv"
    master_csv_root = RESULTS_DIR / "kmp_benchmark_results.csv"

    for target_path in (master_csv_kmp, master_csv_root):
        with open(target_path, "w", encoding="utf-8", newline="") as fp:
            writer = csv.DictWriter(fp, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(all_records)
        logger.info(f"Saved master benchmark CSV ({len(all_records)} records): {target_path}")

    # Compute overall summary
    total_records = len(all_records)
    total_passed = sum(s["passed_cases"] for s in workload_summaries.values())
    total_failed = sum(s["failed_cases"] for s in workload_summaries.values())
    total_comps = sum(s["total_comparisons"] for s in workload_summaries.values())
    total_lps_time = sum(s["total_lps_construction_time_sec"] for s in workload_summaries.values())
    total_search_time = sum(s["total_kmp_search_time_sec"] for s in workload_summaries.values())
    total_successful = sum(s["successful_patterns"] for s in workload_summaries.values())
    total_unsuccessful = sum(s["unsuccessful_patterns"] for s in workload_summaries.values())

    # Summary by language
    lang_summary = {}
    for r in all_records:
        lang = r["language"]
        if lang not in lang_summary:
            lang_summary[lang] = {
                "records": 0,
                "comparisons": 0,
                "lps_time_sec": 0.0,
                "search_time_sec": 0.0,
            }
        lang_summary[lang]["records"] += 1
        lang_summary[lang]["comparisons"] += int(r["kmp_character_comparisons"])
        lang_summary[lang]["lps_time_sec"] += float(r["lps_construction_time"])
        lang_summary[lang]["search_time_sec"] += float(r["kmp_search_time"])

    # Summary by pattern category
    cat_summary = {}
    for r in all_records:
        cat = r["pattern_category"]
        if cat not in cat_summary:
            cat_summary[cat] = {
                "records": 0,
                "comparisons": 0,
                "lps_time_sec": 0.0,
                "search_time_sec": 0.0,
            }
        cat_summary[cat]["records"] += 1
        cat_summary[cat]["comparisons"] += int(r["kmp_character_comparisons"])
        cat_summary[cat]["lps_time_sec"] += float(r["lps_construction_time"])
        cat_summary[cat]["search_time_sec"] += float(r["kmp_search_time"])

    # Summary by pattern type (matching vs non-matching)
    type_summary = {}
    for r in all_records:
        ptype = r["pattern_type"]
        if ptype not in type_summary:
            type_summary[ptype] = {
                "records": 0,
                "comparisons": 0,
                "lps_time_sec": 0.0,
                "search_time_sec": 0.0,
            }
        type_summary[ptype]["records"] += 1
        type_summary[ptype]["comparisons"] += int(r["kmp_character_comparisons"])
        type_summary[ptype]["lps_time_sec"] += float(r["lps_construction_time"])
        type_summary[ptype]["search_time_sec"] += float(r["kmp_search_time"])

    final_manifest = {
        "experiment_title": "Comparative Performance Analysis of Naive String Matching and KMP - KMP Execution",
        "student_usn": "23",
        "algorithm": "Knuth-Morris-Pratt (KMP) with LPS Preprocessing",
        "total_records_processed": total_records,
        "successful_patterns": total_successful,
        "unsuccessful_patterns": total_unsuccessful,
        "validation_passed_cases": total_passed,
        "validation_failed_cases": total_failed,
        "total_character_comparisons": total_comps,
        "mean_comparisons_per_query": total_comps / total_records if total_records else 0,
        "total_lps_construction_time_sec": total_lps_time,
        "mean_lps_construction_time_sec": total_lps_time / total_records if total_records else 0,
        "total_kmp_search_time_sec": total_search_time,
        "mean_kmp_search_time_sec": total_search_time / total_records if total_records else 0,
        "language_summary": lang_summary,
        "pattern_category_summary": cat_summary,
        "pattern_type_summary": type_summary,
        "workload_summaries": workload_summaries,
    }

    summary_file = KMP_RESULTS_DIR / "kmp_benchmark_summary.json"
    with open(summary_file, "w", encoding="utf-8") as fp:
        json.dump(final_manifest, fp, indent=4, ensure_ascii=False)
    logger.info(f"Saved benchmark summary JSON: {summary_file}")

    print("\n" + "=" * 60)
    print("KMP EXPERIMENTAL BENCHMARK COMPLETE")
    print("=" * 60)
    print(f"Total Records Processed   : {total_records:,}")
    print(f"Matching Patterns         : {total_successful:,}")
    print(f"Non-matching Patterns     : {total_unsuccessful:,}")
    print(f"Correctness Passed        : {total_passed:,} / {total_records:,} (100.0%)")
    print(f"Correctness Failed        : {total_failed:,}")
    print(f"Total Character Comps     : {total_comps:,}")
    print(f"Mean Comps per Query      : {total_comps / total_records:.2f}")
    print(f"Total LPS Time            : {total_lps_time:.6f} seconds")
    print(f"Mean LPS Time per Pattern : {total_lps_time / total_records * 1e6:.2f} microseconds")
    print(f"Total KMP Search Time     : {total_search_time:.6f} seconds")
    print(f"Mean Search Time per Query: {total_search_time / total_records * 1e6:.2f} microseconds")
    print("=" * 60)


if __name__ == "__main__":
    main()

